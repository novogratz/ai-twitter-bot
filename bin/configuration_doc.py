#!/usr/bin/env python3
"""Generate the settings reference of docs/CONFIGURATION.md from
src/core/settings.py.

The reference sits between the BEGIN and END markers of the doc; the rest of
the page is written by hand. tests/core/test_settings.py fails while the doc
and the declarations disagree.

Usage:
  uv run python bin/configuration_doc.py           # exit 1 if the doc is stale
  uv run python bin/configuration_doc.py --write   # rewrite the reference
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from src.core import settings  # noqa: E402

DOC = os.path.join(ROOT, "docs", "CONFIGURATION.md")
BEGIN = "<!-- BEGIN settings reference: generated by bin/configuration_doc.py --write, do not edit -->"
END = "<!-- END settings reference -->"
SCRIPTS = ("operator_cycle.sh", "bot_watchdog.sh")


def _default(setting) -> str:
    if setting.name in settings.MODEL_DEFAULTS:
        return "unset: `MODEL_DEFAULTS`"
    value = setting.default
    if value is None:
        return "unset"
    if value == "":
        return "blank"
    if setting.type is bool:
        return "`1`" if value else "`0`"
    return f"`{value}`"


def _bounds(setting) -> str:
    bounds = []
    if setting.floor is not None:
        bounds.append(f"floor `{settings._show(setting, setting.floor)}`")
    if setting.ceiling is not None:
        bounds.append(f"ceiling `{settings._show(setting, setting.ceiling)}`")
    return ", ".join(bounds)


def _row(setting) -> str:
    return (f"| `{setting.name}` | {settings._kind(setting)} | {_default(setting)} | "
            f"{_bounds(setting)} | {setting.description} |")


def render() -> str:
    """The reference, markers included."""
    header = ["| Setting | Type | Default | Bounds | Description |", "|---|---|---|---|---|"]
    used = [s for s in settings.DECLARED.values() if s.name not in settings.UNUSED]
    unused = [s for s in settings.DECLARED.values() if s.name in settings.UNUSED]
    providers = sorted({p for table in settings.MODEL_DEFAULTS.values() for p in table})
    lines = [BEGIN, "", "## Settings reference", "",
             "Every setting `src/core/settings.py` declares, in declaration order. A value",
             "past a bound is brought back to it and logged as a `[SETTINGS]` warning.", "",
             *header, *map(_row, used), "",
             "### `MODEL_DEFAULTS`: the model of a CLI when its setting is unset", "",
             "| Setting | " + " | ".join(providers) + " |",
             "|---|" + "---|" * len(providers)]
    for name, table in settings.MODEL_DEFAULTS.items():
        lines.append(f"| `{name}` | " + " | ".join(f"`{table[p]}`" if p in table else "" for p in providers) + " |")
    lines += ["", "### No effect: remove from `.env`", "",
              "No code reads these any more. They stay declared so a `.env` that still",
              "sets them starts; delete them from it.", "",
              *header, *map(_row, unused), "",
              "### Keys the shell scripts read", "",
              "Not read by the engine: these scripts read them after sourcing `.env`.", "",
              "| Key | Read by |", "|---|---|"]
    texts = {}
    for name in SCRIPTS:
        with open(os.path.join(ROOT, name)) as f:
            texts[name] = f.read()
    for key in sorted(settings.SCRIPT_KEYS):
        readers = ", ".join(f"`{name}`" for name, text in texts.items() if "${" + key in text)
        lines.append(f"| `{key}` | {readers} |")
    lines += ["", END]
    return "\n".join(lines)


def current(text: str) -> str:
    """The reference block of `text`, markers included, or '' without one."""
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        return ""
    return text[start:end + len(END)]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="rewrite the reference in docs/CONFIGURATION.md")
    args = parser.parse_args()
    with open(DOC) as f:
        text = f.read()
    block = current(text)
    if not block:
        print(f"{DOC}: no {BEGIN!r} ... {END!r} block", file=sys.stderr)
        return 1
    fresh = render()
    if block == fresh:
        return 0
    if not args.write:
        print("docs/CONFIGURATION.md is stale: run bin/configuration_doc.py --write", file=sys.stderr)
        return 1
    with open(DOC, "w") as f:
        f.write(text.replace(block, fresh))
    return 0


if __name__ == "__main__":
    sys.exit(main())
